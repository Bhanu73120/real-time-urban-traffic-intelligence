import argparse
from pyspark.sql.functions import col, row_number
from pyspark.sql.window import Window

from streaming.spark.spark_session import create_spark_session
from streaming.spark.transformations.silver_transform import (
    transform_bronze_to_silver
)

BRONZE_PATH = "s3a://traffic-data-lake/bronze/airflow_vehicle_events_v2/"
SILVER_PATH = "s3a://traffic-data-lake/silver/vehicle_events/"
QUARANTINE_PATH = "s3a://traffic-data-lake/quarantine/vehicle_events/"
EXPECTED_EVENTS = 50

def parse_args():
    parser = argparse.ArgumentParser(
        description="Process vehicle events for one demo run."
    )

    parser.add_argument(
        "--run-id",
        required=True,
        help="Run ID generated by the traffic simulator.",
    )

    return parser.parse_args()


def main():
    args = parse_args()
    current_run_id = args.run_id

    print(f"Processing demo run: {current_run_id}")

    spark = create_spark_session()

    try:
        bronze_df = spark.read.parquet(BRONZE_PATH)

        print("Bronze records:", bronze_df.count())

        validated_df = transform_bronze_to_silver(bronze_df)
        validated_df = validated_df.filter(
           col("run_id") == current_run_id
        )

        print("Current demo records:", validated_df.count())

        if validated_df.limit(1).count() == 0:
           raise ValueError(
                f"No Bronze events found for run_id: {current_run_id}"
           )

        valid_df = validated_df.filter(
            col("validation_status") == "VALID"
        )

        rejected_df = validated_df.filter(
            col("validation_status") == "REJECTED"
        )

        # Keep the latest record for each event_id.
        window_spec = (
            Window.partitionBy("event_id")
            .orderBy(
                col("kafka_timestamp").desc(),
                col("kafka_partition").desc(),
                col("kafka_offset").desc()
            )
        )

        silver_df = (
            valid_df
            .withColumn("row_num", row_number().over(window_spec))
            .filter(col("row_num") == 1)
            .drop("row_num")
            .select(
                "run_id",
                "event_id",
                "vehicle_id",
                "road_id",
                "event_timestamp",
                "latitude",
                "longitude",
                "speed_kmph",
                "direction",
                "vehicle_type",
                "kafka_topic",
                "kafka_partition",
                "kafka_offset",
                "kafka_timestamp"
            )
        )


        silver_count = silver_df.count()
        rejected_count = rejected_df.count()

        print(f"Silver records: {silver_count}")
        print(f"Rejected records: {rejected_count}")

        if silver_count != EXPECTED_EVENTS:
            raise ValueError(
                f"Silver validation failed for run_id={current_run_id}. "
                f"Expected {EXPECTED_EVENTS} valid unique events, "
                f"but found {silver_count}."
            )

        if rejected_count != 0:
            raise ValueError(
                f"Silver validation failed: "
                f"{rejected_count} rejected events found."
            )

        print("Silver validation PASSED: 50 valid unique events.")

        silver_df.write.mode("overwrite").parquet(SILVER_PATH)

        rejected_df.write.mode("overwrite").parquet(QUARANTINE_PATH)

        print("Silver and quarantine datasets written successfully.")


    finally:
        spark.stop()


if __name__ == "__main__":
    main()